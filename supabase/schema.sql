-- Skema MVP Tomat Smart Farming.
-- File ini aman dijalankan ulang: tabel, indeks, dan policy tidak dibuat dua kali.

-- Telemetri yang dikirim ESP32.
create table if not exists public.telemetry (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text not null default 'kebun-1',
  adc integer not null,
  persen integer not null,
  suhu real,
  hum real,
  pompa boolean not null,
  mode text not null check (mode in ('auto', 'manual')),
  state text not null check (state in ('IDLE', 'MENYIRAM', 'MERESAP', 'PENGAMAN'))
);

-- Catatan setiap penyiraman yang dikirim ESP32.
create table if not exists public.pump_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text not null,
  durasi_ms integer not null,
  sumber text not null check (sumber in ('auto', 'manual', 'watchdog'))
);

-- Perintah dari website. Firmware memutuskan apakah perintah aman dijalankan.
create table if not exists public.commands (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text not null,
  cmd text not null check (cmd in ('auto', 'manual', 'pump_on', 'pump_off')),
  done boolean not null default false,
  hasil text
);

-- Indeks untuk pembacaan data terbaru per perangkat.
create index if not exists telemetry_device_id_created_at_idx
  on public.telemetry (device_id, created_at desc);

create index if not exists pump_events_device_id_created_at_idx
  on public.pump_events (device_id, created_at desc);

-- Mempercepat kueri firmware: perintah aktif untuk satu perangkat, urut id, satu baris.
create index if not exists commands_pending_device_id_id_idx
  on public.commands (device_id, id)
  where done = false;

-- Semua tabel API wajib memakai Row Level Security.
alter table public.telemetry enable row level security;
alter table public.pump_events enable row level security;
alter table public.commands enable row level security;

-- Hapus hak default lalu berikan hanya hak minimum yang diperlukan.
revoke all on table public.telemetry from anon, authenticated;
revoke all on table public.pump_events from anon, authenticated;
revoke all on table public.commands from anon, authenticated;
revoke all on sequence public.telemetry_id_seq from anon, authenticated;
revoke all on sequence public.pump_events_id_seq from anon, authenticated;
revoke all on sequence public.commands_id_seq from anon, authenticated;

-- ESP32 (anon) hanya dapat memasukkan telemetri dan event pompa.
grant insert on table public.telemetry to anon;
grant insert on table public.pump_events to anon;
grant usage on sequence public.telemetry_id_seq to anon;
grant usage on sequence public.pump_events_id_seq to anon;

-- Pengguna login hanya dapat membaca data telemetri dan event pompa.
grant select on table public.telemetry to authenticated;
grant select on table public.pump_events to authenticated;

-- Kolom minimum untuk GET commands firmware v1.1.6.
-- RLS tetap membatasi baris pada usia command, bukan pada nilai done.
grant select (id, device_id, cmd, created_at, done) on table public.commands to anon;
grant update (done, hasil) on table public.commands to anon;

-- Pengguna login dapat membaca perintah dan membuat perintah baru yang belum selesai.
-- Kolom created_at dan id sengaja tidak diberi hak insert agar waktu perintah berasal dari server.
grant select on table public.commands to authenticated;
grant insert (device_id, cmd, done) on table public.commands to authenticated;
grant usage on sequence public.commands_id_seq to authenticated;

-- Policy dibuat ulang agar perubahan policy dapat dijalankan berulang kali.
drop policy if exists "anon dapat memasukkan telemetry" on public.telemetry;
drop policy if exists "authenticated dapat membaca telemetry" on public.telemetry;
drop policy if exists "anon dapat memasukkan pump events" on public.pump_events;
drop policy if exists "authenticated dapat membaca pump events" on public.pump_events;
drop policy if exists "anon dapat membaca commands aktif" on public.commands;
drop policy if exists "anon dapat menyelesaikan commands aktif" on public.commands;
drop policy if exists "authenticated dapat membaca commands" on public.commands;
drop policy if exists "authenticated dapat membuat commands baru" on public.commands;

create policy "anon dapat memasukkan telemetry"
  on public.telemetry for insert to anon
  with check (true);

create policy "authenticated dapat membaca telemetry"
  on public.telemetry for select to authenticated
  using (true);

create policy "anon dapat memasukkan pump events"
  on public.pump_events for insert to anon
  with check (true);

create policy "authenticated dapat membaca pump events"
  on public.pump_events for select to authenticated
  using (true);

-- Policy SELECT diperlukan agar PATCH anon dapat memeriksa baris hasil update.
-- Jangan membatasi ke done=false: filter itu sudah ada di GET firmware, sedangkan
-- PostgREST tetap membutuhkan SELECT atas baris yang baru menjadi done=true.
create policy "anon dapat membaca commands aktif"
  on public.commands for select to anon
  using (
    created_at >= now() - interval '2 minutes'
  );

-- Firmware hanya dapat mengubah done dan hasil (dibatasi oleh GRANT),
-- dan nilai akhir harus done = true sebelum batas dua menit berlalu.
create policy "anon dapat menyelesaikan commands aktif"
  on public.commands for update to anon
  using (
    done = false
    and created_at >= now() - interval '2 minutes'
  )
  with check (
    done = true
    and created_at >= now() - interval '2 minutes'
  );

create policy "authenticated dapat membaca commands"
  on public.commands for select to authenticated
  using (true);

create policy "authenticated dapat membuat commands baru"
  on public.commands for insert to authenticated
  with check (done = false);
